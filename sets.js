       name:   "どうろ ひょうしき",   // 設定画面に出す名前
       title:  "sets/どうぶつ/看板.png", // 看板の絵。書かなければ共通の看板になります
       folder: "sets/どうぶつ/",       // 絵をまとめて入れたフォルダ（末尾に / を付ける）
       voice:  "voice/hyoushiki/",   // 録音した声を置くフォルダ（無くてもOK）
